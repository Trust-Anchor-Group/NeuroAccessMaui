namespace NeuroAccess.Nfc.TravelDocuments.ISO19794
{
	/// <summary>
	/// ISO 19794-5 eye colour enumeration.
	/// </summary>
	public enum EyeColour
	{

		/// <summary>
		/// Not specified Used when eye color cannot be determined
		/// </summary>
		Unknown = 0,

		/// <summary>
		/// Blue
		/// </summary>
		Blue = 1,

		/// <summary>
		/// Brown
		/// </summary>
		Brown = 2,

		/// <summary>
		/// Green
		/// </summary>
		Green = 3,

		/// <summary>
		/// Gray
		/// </summary>
		Gray = 4,

		/// <summary>
		/// Mixed tones (green/brown)
		/// </summary>
		Hazel = 5,

		/// <summary>
		/// Rare, typically for albanism
		/// </summary>
		Red = 6,

		/// <summary>
		/// For unusual or non‑standard colors
		/// </summary>
		Other = 7
	}
}
